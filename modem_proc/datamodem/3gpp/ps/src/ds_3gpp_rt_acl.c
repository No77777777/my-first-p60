/*===========================================================================
FUNCTION DS_3GPP_RT_ACL_DETERMINE_CALL_TYPE_TO_BE_ORIGINATED

DESCRIPTION
  This functions determines the call type to be originated based on pdp 
  profile type, policy provided by application and ipv6 failover mode nv 
  item. 
  Processing is done as per Net Policy Enforcement table in IPV6 design 
  document.

PARAMETERS
  context_info -- pdp context information for the call 
  policy_info_ptr -- network policy provided by application

DEPENDENCIES
  None.

RETURN VALUE
  ds_umts_originate_call_e_type - V4, V6, PPP or ANY if call type to be 
                                  originated is valid.
  DS_UMTS_PDP_TYPE_FAIL - Otherwise

SIDE EFFECTS 
  None.
===========================================================================*/
ds_pdn_context_type_e ds_3gpp_rt_acl_determine_call_type_to_be_originated
(
  const ds_umts_pdp_context_type  *context_info_p,  /* PDP context info*/
  const acl_policy_info_type*      policy_info_ptr
)
{
  ds_pdn_context_type_e  call_type_orig; /* call type to originate*/
  ds_3gppi_local_err_val_e_type    local_err = DS_3GPPI_LOCAL_ERR_VAL_NONE;
/*- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/
  if(context_info_p == NULL || policy_info_ptr == NULL)
  {
    DS_3GPP_ERROR_LOG_2("Invalid input: Context type 0xx policy info 0xx",
                           context_info_p, policy_info_ptr);
    call_type_orig= DS_3GPP_PDP_TYPE_FAIL;
    return call_type_orig;
  }

  switch(context_info_p->pdp_type)
  {
    case DS_UMTS_PDP_IPV4:
    {
      switch(policy_info_ptr->ip_family)
      {
        case IPV4_ADDR:
        case IP_ANY_ADDR:
        case IFACE_UNSPEC_ADDR_FAMILY:
          call_type_orig= DS_3GPP_PDP_TYPE_IPV4;
          break;

        case IPV6_ADDR:
        default:
          DS_3GPP_MSG0_LOW("Invalid IP Addr type requested in Policy");
          call_type_orig= DS_3GPP_PDP_TYPE_FAIL;
          //local_err = DS_3GPPI_LOCAL_ERR_VAL_0;
          break;
       }
    }
    break;

    case DS_UMTS_PDP_PPP:
    {
      if(policy_info_ptr->ip_family == IPV4_ADDR)
      {
        call_type_orig= DS_3GPP_PDP_TYPE_PPP;
      }
      else
      {
        DS_3GPP_MSG1_LOW("Invalid IP family req in Policy for PPP call %d",
                           policy_info_ptr->ip_family);
        call_type_orig= DS_3GPP_PDP_TYPE_FAIL;
        local_err = DS_3GPPI_LOCAL_ERR_VAL_1;
      }
    }
    break;

    case DS_UMTS_PDP_IPV6:
    {
      switch( policy_info_ptr->ip_family )
      {
        case IPV6_ADDR:
        case IP_ANY_ADDR:
        case IFACE_UNSPEC_ADDR_FAMILY:
          call_type_orig = DS_3GPP_PDP_TYPE_IPV6;
          break;

        case IPV4_ADDR:
        default:
          DS_3GPP_MSG0_LOW("Invalid IP Addr type or Policy type requested");
          call_type_orig= DS_3GPP_PDP_TYPE_FAIL;
          //local_err = DS_3GPPI_LOCAL_ERR_VAL_2;
          break;
      }
    }
    break;

    case DS_UMTS_PDP_IPV4V6:
    {
      switch( policy_info_ptr->ip_family )
      {
        case IPV6_ADDR:
          call_type_orig = DS_3GPP_PDP_TYPE_IPV6;
          break;
        case IPV4_ADDR:
          call_type_orig = DS_3GPP_PDP_TYPE_IPV4;
          break;
        case IP_ANY_ADDR:
        case IFACE_UNSPEC_ADDR_FAMILY:
          call_type_orig = DS_3GPP_PDP_TYPE_IP_ANY;
          break;
        default:
          DS_3GPP_MSG0_LOW("Invalid IP Addr type or Policy type requested");
          call_type_orig= DS_3GPP_PDP_TYPE_FAIL;
          local_err = DS_3GPPI_LOCAL_ERR_VAL_3;
          break;
      }
    }
    break;

   default:
      DS_3GPP_MSG0_LOW("Invalid Context type requested");
      local_err = DS_3GPPI_LOCAL_ERR_VAL_4;
     call_type_orig= DS_3GPP_PDP_TYPE_FAIL;
     break;
  }

  if(local_err != DS_3GPPI_LOCAL_ERR_VAL_NONE)
  {
    DS_3GPP_ERROR_LOG_3_EX(ds3gsubsmgr_subs_id_ds_to_cm(policy_info_ptr->subs_id),
                       "determine_call_type_to_be_originated: err d "
                       "IP addr type in pdn context: d in policy d",
                       local_err,
                       context_info_p->pdp_type,
                       policy_info_ptr->ip_family);
  }

  return call_type_orig;
} /* ds_3gpp_rt_acl_determine_call_type_to_be_originated() */
#endif /* FEATURE_DATA_PS_IPV6 */

/*===========================================================================
FUNCTION DS_3GPP_RT_ACL_CHECK_IP_COMPATIBILITY

DESCRIPTION
  Check IP addr compatibility

PARAMETERS  
  req_ip_family : Iface ptr
  if_ip_family  : fallback deny reaon

DEPENDENCIES 
  None.

RETURN VALUE 
  boolean 

SIDE EFFECTS 
  None.
===========================================================================*/
static boolean ds_3gpp_rt_acl_check_ip_compatibility
(
  ps_iface_addr_family_type  req_ip_family,
  ps_iface_addr_family_type  if_ip_family,
  sys_modem_as_id_e_type     subs_id  
)
{
  boolean ret = FALSE;
  ds_3gppi_local_err_val_e_type    local_err = DS_3GPPI_LOCAL_ERR_VAL_NONE;
/*- - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -*/
  DS_3GPP_MSG2_LOW( "chk IP compat: addr type req [%d], if [%d]",
                     req_ip_family, if_ip_family);

  switch(if_ip_family)
  {
    case IPV4_ADDR:
    {
      switch(req_ip_family)
      {
        case IPV4_ADDR:
        case IP_ANY_ADDR:
        case IFACE_UNSPEC_ADDR_FAMILY:
          ret = TRUE;
          break;

        case IPV6_ADDR:
        default:
          DS_3GPP_MSG1_LOW("chk IP compat: failed, IP Addr type "
                            "[%d] req in Policy", req_ip_family);
          local_err = DS_3GPPI_LOCAL_ERR_VAL_0;
          ret = FALSE;
          break;
      }
    }/*IPv4*/
    break;

    case IPV6_ADDR:
    {
      switch(req_ip_family)
      {
        case IPV6_ADDR:
        case IP_ANY_ADDR:
        case IFACE_UNSPEC_ADDR_FAMILY:
          ret = TRUE;
          break;

        case IPV4_ADDR:
        default:
          DS_3GPP_MSG0_LOW("chk IP compat: failed, IP Addr type [%d] req in Policy");
          local_err = DS_3GPPI_LOCAL_ERR_VAL_1;
          ret = FALSE;
          break;
      }
    }/*IPv6*/
    break;

    case IFACE_UNSPEC_ADDR_FAMILY:
    case IP_ANY_ADDR:
    {
      switch( req_ip_family )
      {
        case IPV6_ADDR:
        case IPV4_ADDR:
        case IP_ANY_ADDR:
        case IFACE_UNSPEC_ADDR_FAMILY:
          ret = TRUE;
          break;

        default:
          DS_3GPP_MSG0_LOW("chk IP compat: failed, IP Addr type [%d] req in Policy");
          local_err = DS_3GPPI_LOCAL_ERR_VAL_2;
          ret = FALSE;
          break;
      }
    }
    break;

    default:
      DS_3GPP_MSG0_LOW("Invalid Iface IP family type");
      local_err = DS_3GPPI_LOCAL_ERR_VAL_3;
      ret = FALSE;
      break;
  }

  if(local_err != DS_3GPPI_LOCAL_ERR_VAL_NONE)
  {
    DS_3GPP_ERROR_LOG_3_EX(subs_id,
                           "check_ip_compatibility: err d from policy: d from "
                           "iface: d ",
                           local_err, req_ip_family, if_ip_family);
  }
  return ret;
}/* ds_3gpp_rt_acl_check_ip_compatibility() */

