/*!
  @brief
  Measures Rx parameters
 
  @details
  This function is the handler function to configure Radio to given mode of operation. When a TX CONTROL command is
  received, it is broken into two parts
  #- RF devices that are no longer used/removed
  #- RF devices that are currently used and being re-tuned /  RF devices that are newly used and must be woken up
 
  Each technology is expected to reconfigure their driver/devices in this order. Devices which are no longer used after
  a TX_CONTROL are returned to the system for other subscriptions to use in the future. A TX_CONTROL command 
  received for a subscription+tech which is currently configured and contains no carriers means to release all resources
 
  @param command_data
  Pointer to the structure containing command specific dispatch command
 
  @return
  Response Packet for TX CONTROL command
*/
static boolean
tx_control_handler
(
  struct ftm_rf_test_command_data_t *command
)
{
  boolean ret_val = TRUE;
  ftm_rf_test_tx_control_command_data_t *command_data;
  ftm_rf_test_req_type *req_data;
  ftm_rf_test_tx_control_rsp_payload_type *rsp_payload;
  ftm_rf_test_field_error_code_mask_type error_code = 0;
  ftm_rf_test_field_error_code_mask_type ec_unpack = 0;
  ftm_rf_test_field_error_code_mask_type ec_tech_cb = 0;
  ftm_rf_test_tx_control_mode_data_t* tx_control_data;
  uint32 meas_idx = 0;
  uint32 payload_size = 0;
  uint32 measurement_results_size = 0;
  boolean tech_override = FALSE;

  /* Param validation */
  if ( ( command == NULL ) || ( command->dispatch_data == NULL ) ||
       ( command->diag_request_data == NULL ) )
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]radio_config_handler: Null param" );
    ret_val = FALSE;
  } /* if ( ( command_instance == NULL ) || ( command_instance->sw_command == NULL ) ||
       ( command_instance->diag_request_data == NULL ) ) */

  if ( ret_val == TRUE )
  {
    /* Param validation */
    if ( command->technology >= RFM_NUM_MODES )
    {
      FTM_MSG_1( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]radio_config_handler: Bad Tech %d",
                 command->technology);
      ret_val = FALSE;
    } /* if ( command_instance->technology >= RFM_NUM_MODES ) */
  }

  if ( ret_val == TRUE )
  {  
    /* Get TX CONTROL Data */
    command_data = (ftm_rf_test_tx_control_command_data_t*)(command->dispatch_data->command_data);

    /* Get Diag Request Data */
    req_data = command->diag_request_data;

    /* Make sure that the Radio config Data and diag request data is not NULL, before proceeding */
    if ( ( command_data == NULL ) || ( req_data == NULL) )
    { 
      FTM_MSG( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]tx_control_handler: Null RC / REQ Data" );
      error_code |= (1<<FTM_RF_TEST_TX_EC_ERROR);
      ret_val = FALSE;
    } /* if !( ( radio_config_data != NULL ) && ( req_data != NULL ) ) */
  }

  if ( ret_val == TRUE ) 
  {
    tx_control_data = &(command_data->mode_data[command->technology]); 

    /* reset all data structs before populating unpacked data and payload */

    if ( tx_control_data->unpacked_data != NULL )
    {
      modem_mem_free( tx_control_data->unpacked_data, MODEM_MEM_CLIENT_RFA );
    }

    tx_control_data->unpacked_data_num = 0;
    tx_control_data->unpacked_data = NULL;
  
    /* Tech has the option to override the common unpack & dispatch. Tech has to allocate the response using the
    rsp_alloc_cb provided */        
    if ( tx_control_data->advanced_tech_callback_fp != NULL )
    {
      ftm_rf_test_tx_control_advanced_dispatch_data_type tech_override_data;

      memset(&tech_override_data, 0, sizeof(ftm_rf_test_tx_control_advanced_dispatch_data_type) );

      tech_override_data.req_prop_num = req_data->payload.num_of_properties;
      tech_override_data.req_prop_list = &(req_data->payload.property_data);
      
      ec_tech_cb = tx_control_data->advanced_tech_callback_fp( &tech_override_data );
      
    }
    else /* if ( tx_control_data->override_callback_fp == NULL )*/
    {
      /* Unpack data */
      ec_unpack = ftm_rf_test_unpack_property_list( 
                                        req_data->payload.num_of_properties, 
                                        &(req_data->payload.property_data),
                                        tx_control_data,
                                        TRUE,
                                        tx_control_req_default_unpack_cb,
                                        tx_control_req_default_delimiter_cb);
      
      /* Continue if the UNPACK error code is 0 */
      if ( ec_unpack == 0 )
      {
        /* Call Tech callback */
        if ( tx_control_data->default_callback_fp != NULL )
        {
          ec_tech_cb = tx_control_data->default_callback_fp( tx_control_data->unpacked_data, 
                                                             tx_control_data->unpacked_data_num );

        } /* if ( tx_control_data->mode_data[command_instance->technology].callback_fp != NULL ) */
        else
        {
          ec_tech_cb = (1<<FTM_RF_TEST_TX_EC_SUCCESS);
        } /* if ! ( tx_control_data->mode_data[command_instance->technology].callback_fp != NULL ) */
        
      } /* if ( ec_unpack == 0 ) */
      else
      {
        FTM_MSG( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]tx_control_handler: Unpack failure" );
      }

    }/* if ( tx_control_data->override_callback_fp == NULL ) */

    /* Accumulate error code */
    error_code |= ec_unpack;
    error_code |= ec_tech_cb;

    if ( error_code != 0 )
    {
      ret_val = FALSE;
    } /* if ( error_code != 0 ) */

    FTM_MSG_1( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL][DISPATCH]: [ErrorCode 0x%x]", error_code );
  }

  /* Populate respoonse payload, if tech did not override common unpack & dispatch */
  if ( ret_val == TRUE )
  {
    uint32 payload_size = sizeof(tx_control_data->rsp_payload_data);

    tx_control_data->rsp_payload_data.error_code = error_code;

    ret_val = ftm_rf_test_alloc_response_helper( &(command->response_data),
                                                 &(tx_control_data->rsp_payload_data),
                                                 payload_size );
  }/* if ( ret_val == TRUE && tech_overriden == FALSE )*/
  
  return ret_val; 

} /* radio_config_handler */

