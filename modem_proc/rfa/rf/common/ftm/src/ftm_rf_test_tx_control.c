/*!
  @brief
  Unpack TX CONTROL command packet to default format
 
  @details
  This function unpacks the TX CONTROL command. The unpack process will result on two structure - one containing
  the list of devices which needs to be dropped by the tech; and other containining the list of devices and
  configuration data to be added and reconfigured. Some rules assumed during unpacking are as follows
  #- List of properties are grouped into different groups which is delimited by Rx or Tx carrier property
  #- Each group cannot have more than one entries of "same" property
  #- The devices not present in the new command config data as compared to previous command config data will be
     assumed to the devices to be dropped.
 
  @param num_of_props
  Number of properties in teh property list
 
  @param property_list
  Pointer to the property list
 
  @param unpack_data
  Structrue where the unpack data will be stored
 
  @param last_unpack_data
  Pointer last unpack data used to diff with the new command config to generate the drop list
 
  @param subscriber
  Subscriber number
 
  @param debug_mode
  Flag indicating the debug mode
 
  @return
  Error code generated by this function. The unpack data is valid only if the error code is 0.
*/
static ftm_rf_test_field_error_code_mask_type
tx_control_req_default_unpack_cb(uint32 num_of_props,
                                 ftm_rf_test_property_data_type * property_list,
                                 void* command_data,
                                 boolean debug_mode )
{
  ftm_rf_test_field_error_code_mask_type error_code = 0;
  ftm_rf_test_property_data_type *prop_ptr = NULL;
  uint32 prop_index = 0;
  rfm_device_enum_type device = RFM_INVALID_DEVICE;

  /*------------------------------------------------------------------------------------------------------------------*/
  /* Variables used to temporarily store the unpacked data; until they are pushed to the unpack structure. */
  /* These variables must be reset to default value before starting to unpack a property group. */
  /*------------------------------------------------------------------------------------------------------------------*/
  ftm_rf_test_tx_control_unpacked_data_t* curr_unpacked_data= NULL;
  ftm_rf_test_tx_control_mode_data_t* tx_control_data = (ftm_rf_test_tx_control_mode_data_t*)command_data;

  if ( property_list == NULL || tx_control_data == NULL )
  {
    FTM_MSG( FTM_HIGH, "[FTM.RFTEST][TX_CONTROL]tx_control_unpack: Null param " );
    error_code |= (1<<FTM_RF_TEST_TX_EC_ERROR);
    return error_code;
  } /* if ( ( property_list == NULL ) || ( tx_control_data == NULL ) ) */

  tx_control_data->unpacked_data = modem_mem_realloc(
                     tx_control_data->unpacked_data,
                     (tx_control_data->unpacked_data_num+1)* sizeof(ftm_rf_test_tx_control_unpacked_data_t),
                     MODEM_MEM_CLIENT_RFA );

  if ( tx_control_data->unpacked_data == NULL )
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]tx_control_unpack: failed to grow unpacked_data " );
    error_code |= (1<<FTM_RF_TEST_TX_EC_ERROR);
    return error_code;
  }

  curr_unpacked_data = &(tx_control_data->unpacked_data[tx_control_data->unpacked_data_num]);

  memset( curr_unpacked_data , 0 , sizeof(ftm_rf_test_tx_control_unpacked_data_t) );
 
  tx_control_data->unpacked_data_num++;

  if ( debug_mode == TRUE )
  {
    FTM_MSG_3(FTM_MED,"ftm_rf_test_tx_control_process_action: EXTRACT ACTION [%d][@0x%08x]FROM[0x%08x]",
                      tx_control_data->unpacked_data_num,
                      tx_control_data->unpacked_data,
                      curr_unpacked_data );
  }

  /*------------------------------------------------------------------------------------------------------------------*/
  /* Reset the local variables to store the unpackes data for each property group */  
  /*------------------------------------------------------------------------------------------------------------------*/
  /*------------------------------------------------------------------------------------------------------------------*/

  /* Initialize Propert pointer */
  prop_ptr = property_list;

  /*------------------------------------------------------------------------------------------------------------------*/
  /* Populate the Device to Measure list */
  /*------------------------------------------------------------------------------------------------------------------*/
  /* Continue, if the number if properties is not 0 */
  if ( num_of_props != 0 )
  {
    /* Loop thrrough the number of properties. Loop is allowed to till num_of_props; to latch the last propert group */
    for ( prop_index = 0; prop_index < num_of_props; prop_index++ )
    {
      /* If the debug mode is enabled, then print property information */
      if ( debug_mode == TRUE )
      {
        FTM_MSG_3( FTM_HIGH, "[FTM.RFTEST][TX_CONTROL][UNPACK]: [%2d][Property %3d][Value %8d]", 
                   prop_index, prop_ptr->property_type, prop_ptr->property_val );
      } /* if ( debug_mode == TRUE ) */

      switch ( prop_ptr->property_type )
      {
      case FTM_TX_CONTROL_PROP_RFM_DEVICE:           
        device = prop_ptr->property_val;
        if ( device < RFM_MAX_WAN_DEVICES )
        {
          curr_unpacked_data->input.device = device;          
        } /* if (  rfm_device_pri < RFM_MAX_WAN_DEVICES  ) */
        else
        {
          FTM_MSG(FTM_ERROR,"ftm_rf_test_tx_control_unpack_callback: invalid device");
        }
        break;

      case FTM_TX_CONTROL_PROP_TX_CARRIER:
        curr_unpacked_data->input.carrier = prop_ptr->property_val;        
        break;

      case FTM_TX_CONTROL_PROP_TX_ACTION:
        curr_unpacked_data->input.tx_action = prop_ptr->property_val;
        break;

      case FTM_TX_CONTROL_PROP_TX_POWER:
        curr_unpacked_data->input.tx_power = prop_ptr->property_val;        
        break;

      case FTM_TX_CONTROL_PROP_RB_CONFIG:
        curr_unpacked_data->input.rb_config = prop_ptr->property_val;        
        break;

      default:
        FTM_MSG_1(FTM_ERROR,"[FTM.RFTEST][TX_CONTROL][UNPACK]: Unrecongnized Property Type %d",  
                  prop_ptr->property_type );
        break;
      } /* switch ( prop_ptr->property_type ) */
    
      /* Increment the poperty pointer */
      prop_ptr++;
    } /* for ( prop_index = 0; prop_index < num_of_props; prop_index++ ) */
  } /* if ( num_of_props != 0 ) */
 
  /*------------------------------------------------------------------------------------------------------------------*/
  /* Error handling */
  /*------------------------------------------------------------------------------------------------------------------*/

  /* If error code is not zero, then clear the unpack data */
  if ( error_code != 0 )
  {
    /* Clear memory for unpack data */
    FTM_MSG_1( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]: [ErrorCode 0x%x] Clearing unpack data",
               error_code );
  } /* if ( error_code != 0 ) */

  return error_code;

} /* tx_control_req_default_unpack_cb */

/*--------------------------------------------------------------------------------------------------------------------*/
/*!
  @brief
  Call back API to allow common unpacker to identify delimter from property list 
*/
static boolean
tx_control_req_default_delimiter_cb
(
   uint32 property_type
)
{
  boolean is_delimiter = FALSE;

  if ( property_type == FTM_TX_CONTROL_PROP_TX_CARRIER )
  {
    is_delimiter = TRUE;
  }
  else
  {
    is_delimiter = FALSE;
  }
  
  return is_delimiter;
}

