/*--------------------------------------------------------------------------------------------------------------------*/
/*!
  @brief
  Register Tech callback
 
  @details
  This function is used to register a tech callback function for TX CONTROL command
 
  @param technology
  Technology for which the callback is to be registered
 
  @param callback_fp
  Callback funtion pointer to be registered
 
  @return
  Flag indicating the status of callback registration
*/
boolean
ftm_rf_test_tx_control_register_default_tech_cb
(
  rfm_mode_enum_type technology,
  ftm_rf_test_tx_control_tech_callback_fp callback_fp
)
{
  ftm_rf_test_command_dispatch_data_t *dispatch_data;
  ftm_rf_test_tx_control_command_data_t *tx_control_data;

  dispatch_data = ftm_rf_test_get_dispatch_data( FTM_RF_TEST_CMD_TX_CONTROL );

  /* Param validation */
  if ( dispatch_data == NULL )
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]ftm_rf_test_tx_control_register_tech_cb: Null param" );
    return FALSE;
  } /* if ( dispatch_data == NULL ) ) */

  /* Param validation */
  if ( technology >= RFM_NUM_MODES )
  {
    FTM_MSG_1( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]ftm_rf_test_tx_control_register_tech_cb: Bad Tech %d",
               technology);
    return FALSE;
  } /* if ( technology >= RFM_NUM_MODES ) */

  tx_control_data = (ftm_rf_test_tx_control_command_data_t*)dispatch_data->command_data;

  if ( tx_control_data == NULL) 
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]ftm_rf_test_tx_control_register_tech_cb: NULL tx_control data %d" );
    return FALSE;
  }
  /* Save callback function */
  tx_control_data->mode_data[technology].default_callback_fp = callback_fp;

  FTM_MSG_1( FTM_HIGH, "[FTM.RFTEST][TX_CONTROL]ftm_rf_test_tx_control_register_tech_cb: Registered for Tech %d",
             technology);

  return TRUE;

} /* ftm_rf_test_tx_control_register_tech_cb */


