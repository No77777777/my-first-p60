/*!
  @brief
  Initialize TX CONTROL Command handler module
 
  @details
  This function initializes the TX CONTROLure command module. Initialization includes, allocating the memory for
  house keeping data for TX CONTROL command and populating the command handler function
 
  @param dispatch_data
  Poitner to dispatch data specific to TX CONTROL command
 
  @return
  Flag indicating the status of TX CONTROL initialization
*/
boolean
ftm_rf_test_tx_control_init
(
  ftm_rf_test_command_dispatch_data_t *dispatch_data
)
{
  boolean ret_val = TRUE;

  /* Param Validation */
  if ( dispatch_data == NULL )
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]ftm_rf_test_tx_control_init: Null param" );
    return FALSE;
  } /* if ( dispatch_data == NULL ) */

  /* Allocate memory for TX CONTROL command handler */ 

  if ( dispatch_data->command_data == NULL )
  {
    dispatch_data->command_data = 
      (void*)modem_mem_alloc( sizeof(ftm_rf_test_tx_control_command_data_t), MODEM_MEM_CLIENT_RFA );
  } /* if ( dispatch_data->command_data == NULL ) */

  if ( dispatch_data->command_data != NULL )
  {
    memset( dispatch_data->command_data, 0, sizeof(ftm_rf_test_tx_control_command_data_t) );
    dispatch_data->command_handler = tx_control_handler;
  } /* if ( dispatch_data->command_data != NULL ) */
  else
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][TX_CONTROL]ftm_rf_test_tx_control_init: Malloc failure" );
    ret_val = FALSE;
  } /* if !( dispatch_data->command_data != NULL ) */

  return ret_val;

} /* ftm_rf_test_tx_control_init */

/*--------------------------------------------------------------------------------------------------------------------*/
/*!
  @brief
  DeInitialize TX CONTROL Command handler module
 
  @details
  This function deinitializes the TX CONTROLure command module. DeInitialization includes, deallocating the memory for
  house keeping data for TX CONTROL command
 
  @param dispatch_data
  Poitner to dispatch data specific to TX CONTROL command
 
  @return
  Flag indicating the status of TX CONTROL deinitialization
*/
boolean
ftm_rf_test_tx_control_deinit
(
  ftm_rf_test_command_dispatch_data_t *dispatch_data
)
{
  boolean ret_val = TRUE;

  /* Param Validation */
  if ( dispatch_data == NULL )
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][RADIO_CONFIG]ftm_rf_test_radio_config_deinit: Null param" );
    return FALSE;
  } /* if ( dispatch_data == NULL ) */

  ftm_rf_test_tx_control_command_data_t * tx_control_data = 
    (ftm_rf_test_tx_control_command_data_t *)dispatch_data->command_data;

  /* Free memory allocated for Radio Config command handler */ 
  if ( tx_control_data != NULL )
  {
    uint8 mode_idx = 0;
    for ( mode_idx = 0; mode_idx < RFM_NUM_MODES; mode_idx ++ )
    {
      if( tx_control_data->mode_data[mode_idx].unpacked_data != NULL )
      {
        modem_mem_free( tx_control_data->mode_data[mode_idx].unpacked_data, MODEM_MEM_CLIENT_RFA );
      }
    }

    modem_mem_free( tx_control_data , MODEM_MEM_CLIENT_RFA );

    dispatch_data->command_data = NULL;
  } /* if ( dispatch_data->command_data != NULL ) */

  dispatch_data->command_handler = NULL;

  return ret_val;

} /* ftm_rf_test_tx_control_deinit */

