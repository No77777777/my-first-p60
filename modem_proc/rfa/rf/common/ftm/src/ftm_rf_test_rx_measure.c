/*!
  @name Repack Rx Measure Data from Default format to payload property format.
  Future development for other formats can be based on this API.

  @brief
  Functions to handle Rx Measure command
*/
/*! @{ */

boolean
rx_measure_rsp_default_response_helper
(
  ftm_rf_test_reponse_data_type* response_allocator_data,
  ftm_rf_test_rx_measure_rsp_payload_type* repacked_payload,
  uint32 repacked_payload_size
)
{
  boolean ret_val = TRUE;
  ftm_rf_test_rx_measure_rsp_payload_type* allocated_rsp;

  if ( repacked_payload == NULL || response_allocator_data == NULL )
  {
    FTM_MSG(FTM_ERROR,"[FTM.RFTEST][RSP][REPACK]: NULL POINTER!");
    ret_val = FALSE;
  }
  else
  {
    /* Create Response packet */
    allocated_rsp = (ftm_rf_test_rx_measure_rsp_payload_type*)response_allocator_data->
             alloc_response_fp( response_allocator_data, 
                                repacked_payload_size+sizeof(repacked_payload->error_code)+sizeof(repacked_payload->number_of_properties));

    /* NULL pointer check */
    if ( allocated_rsp != NULL )
    {
      /* Populate response packet */
      allocated_rsp->error_code = repacked_payload->error_code;
      allocated_rsp->number_of_properties = repacked_payload->number_of_properties;
      /* Mem copy the property list to right after num_of_properties */      
      memscpy( &(allocated_rsp->result_prop_list), repacked_payload_size, repacked_payload->result_prop_list, repacked_payload_size );
    } /* if ( rsp_payload != NULL ) */
    else
    {
      ret_val = FALSE;
      FTM_MSG( FTM_ERROR, "[FTM.RFTEST][RSP][REPACK]: Response malloc failure" );
    } /* if !( rsp_payload != NULL ) */
  }

  return ret_val; 
}/* rx_measure_rsp_default_response_helper */

