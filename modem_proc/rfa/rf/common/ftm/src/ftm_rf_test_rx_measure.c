/*!
  @brief
  Utility API to repack measurement result to property list using default format.
  Future variations can be based on this API.
*/
static boolean
rx_measure_rsp_default_repack_helper
(
  uint32 unpacked_measurement_num,
  ftm_rf_test_rx_measure_unpacked_data_t* unpacked_measurement_list,
  ftm_rf_test_rx_measure_rsp_payload_type* repacked_payload,
  uint32* repacked_payload_size,
  boolean debug_mode
)
{
  uint32 meas_idx;
  boolean ret_val = TRUE;
  
  /* Populate Payload */
  for ( meas_idx = 0; meas_idx < unpacked_measurement_num; meas_idx ++ )
  {
    ftm_rf_test_rx_measure_property_type prop_type;

    for ( prop_type = FTM_RF_MEASURE_PROP_UNASSIGNED; 
          prop_type < FTM_RX_MEASURE_PROP_NUM; prop_type++ )
    {
      if ( unpacked_measurement_list[meas_idx].response_prop_mask[prop_type] == TRUE ) 
      {
        uint32 curr_property_index = repacked_payload->number_of_properties;

        /* Increment number of total properties */
        repacked_payload->number_of_properties++;

        /* Grow memory for number of total properties */
        repacked_payload->result_prop_list = modem_mem_realloc( 
           repacked_payload->result_prop_list, 
           repacked_payload->number_of_properties*sizeof(ftm_rf_test_property_data_type), 
           MODEM_MEM_CLIENT_RFA);      

        if ( repacked_payload->result_prop_list == NULL )
        {
          ERR_FATAL("[FTM.RFTEST][RX_MEASURE] NULL REALLOC POINTER!",0,0,0);        
        }

        memset(&(repacked_payload->result_prop_list[curr_property_index]), 
               0, sizeof(ftm_rf_test_property_data_type)); 

        repacked_payload->result_prop_list[curr_property_index].property_type = prop_type;

        switch ( prop_type )
        {
        case FTM_RX_MEASURE_PROP_RX_CARRIER:
          repacked_payload->result_prop_list[curr_property_index].property_val = 
            unpacked_measurement_list[meas_idx].input.carrier;     
          break;

        case FTM_RX_MEASURE_PROP_RFM_DEVICE:       
          repacked_payload->result_prop_list[curr_property_index].property_val = 
            unpacked_measurement_list[meas_idx].input.device;     
          break;

        case FTM_RX_MEASURE_PROP_AGC:
          repacked_payload->result_prop_list[curr_property_index].property_val = 
            unpacked_measurement_list[meas_idx].output.rxagc;     
          break;

        case FTM_RX_MEASURE_PROP_LNA_GAIN_STATE:
          repacked_payload->result_prop_list[curr_property_index].property_val = 
            unpacked_measurement_list[meas_idx].output.lna_gain_state; 
          break;

        default:
          FTM_MSG_1(FTM_ERROR,"[FTM.RFTEST][RX_MEASURE][REPACK]: Unexpected REPACK Property %d"
                              "NO Value populated %d",  prop_type );
          break;        
        }

        if ( debug_mode == TRUE )
        {
          FTM_MSG_4(FTM_MED, "[FTM.RFTEST][RX_MEASURE][REPACK]: "
                               "[%3d][PROP Type %2d][PROP Value %5d][PROP Value 0x%8x]", 
                     repacked_payload->number_of_properties,
                     repacked_payload->result_prop_list[curr_property_index].property_type,
                     repacked_payload->result_prop_list[curr_property_index].property_val,
                     repacked_payload->result_prop_list[curr_property_index].property_val );
        }
      }/* if ( unpacked_measurement_list[meas_idx].rsp_property_list[prop_idx] == TRUE )  */
      else
      {
        /* Skip packing for non marked property */
        if ( debug_mode == TRUE )
        { 
          FTM_MSG_1(FTM_MED, "[FTM.RFTEST][RX_MEASURE][REPACK]: [PROP TYPE %d] NOT PACKED", prop_type );
        }
      }
    }/* for ( prop_idx = 0; prop_idx < FTM_RX_MEASURE_PROP_NUM; prop_idx++ ) */
  }/* for ( meas_idx = 0; meas_idx < unpacked_measurement_num; meas_idx ++ ) */

  /* Calculate Payload size: Error Code + Num_of_properties + Measurement Data */
  *repacked_payload_size = 
    repacked_payload->number_of_properties*sizeof(ftm_rf_test_property_data_type) ;     

  if ( debug_mode == TRUE ) 
  {
    FTM_MSG_2(FTM_MED,"[FTM.RFTEST][RX_MEASURE][REPACK][TOTAL PAYLOAD SIZE %d][FOR %d PROPS]",
              *repacked_payload_size, repacked_payload->number_of_properties);
  }

  return ret_val;

}/* rx_measure_rsp_default_repack_cb */



