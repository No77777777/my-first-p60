/*!
  @brief
  Measures Rx parameters
 
  @details
  This function is the handler function to configure Radio to given mode of operation. When a Rx Measure command is
  received, it is broken into two parts
  #- RF devices that are no longer used/removed
  #- RF devices that are currently used and being re-tuned /  RF devices that are newly used and must be woken up
 
  Each technology is expected to reconfigure their driver/devices in this order. Devices which are no longer used after
  a RX_MEASURE are returned to the system for other subscriptions to use in the future. A RX_MEASURE command 
  received for a subscription+tech which is currently configured and contains no carriers means to release all resources
 
  @param command_data
  Pointer to the structure containing command specific dispatch command
 
  @return
  Response Packet for Rx Measure command
*/
static boolean
rx_measure_handler
(
  struct ftm_rf_test_command_data_t *command
)
{
  boolean ret_val = TRUE;
  ftm_rf_test_rx_measure_command_data_t *command_data;
  ftm_rf_test_req_type *req_data;
  ftm_rf_test_rx_measure_rsp_payload_type *rsp_payload;
  ftm_rf_test_field_error_code_mask_type error_code = 0;
  ftm_rf_test_field_error_code_mask_type ec_unpack = 0;
  ftm_rf_test_field_error_code_mask_type ec_tech_cb = 0;
  ftm_rf_test_rx_measure_mode_data_t* rx_measure_data;
  uint32 meas_idx = 0;
  uint32 payload_size = 0;
  uint32 measurement_results_size = 0;
  boolean tech_override = FALSE;

  /* Param validation */
  if ( ( command == NULL ) || ( command->dispatch_data == NULL ) ||
       ( command->diag_request_data == NULL ) )
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][RX_MEASURE]radio_config_handler: Null param" );
    ret_val = FALSE;
  } /* if ( ( command_instance == NULL ) || ( command_instance->sw_command == NULL ) ||
       ( command_instance->diag_request_data == NULL ) ) */

  if ( ret_val == TRUE )
  {
    /* Param validation */
    if ( command->technology >= RFM_NUM_MODES )
    {
      FTM_MSG_1( FTM_ERROR, "[FTM.RFTEST][RX_MEASURE]radio_config_handler: Bad Tech %d",
                 command->technology);
      ret_val = FALSE;
    } /* if ( command_instance->technology >= RFM_NUM_MODES ) */
  }

  if ( ret_val == TRUE )
  {  
    /* Get RX Measure Data */
    command_data = (ftm_rf_test_rx_measure_command_data_t*)(command->dispatch_data->command_data);

    /* Get Diag Request Data */
    req_data = command->diag_request_data;

    /* Make sure that the Radio config Data and diag request data is not NULL, before proceeding */
    if ( ( command_data == NULL ) || ( req_data == NULL) )
    { 
      FTM_MSG( FTM_ERROR, "[FTM.RFTEST][RX_MEASURE]rx_measure_handler: Null RC / REQ Data" );
      error_code |= (1<<FTM_RF_TEST_RX_EC_ERROR);
      ret_val = FALSE;
    } /* if !( ( radio_config_data != NULL ) && ( req_data != NULL ) ) */
  }

  if ( ret_val == TRUE ) 
  {
    rx_measure_data = &(command_data->mode_data[command->technology]); 

    /* reset all data structs before populating unpacked data and payload */

    if ( rx_measure_data->rsp_payload_data.result_prop_list != NULL )
    {
      modem_mem_free( rx_measure_data->rsp_payload_data.result_prop_list, MODEM_MEM_CLIENT_RFA );
    }

    if ( rx_measure_data->unpacked_data != NULL )
    {
      modem_mem_free( rx_measure_data->unpacked_data, MODEM_MEM_CLIENT_RFA );
    }

    rx_measure_data->unpacked_data_num = 0;
    rx_measure_data->unpacked_data = NULL;
    rx_measure_data->rsp_payload_data.error_code = 0;
    rx_measure_data->rsp_payload_data.number_of_properties = 0;
    rx_measure_data->rsp_payload_data.result_prop_list = NULL;
  
    /* Tech has the option to override the common unpack & dispatch. Tech has to allocate the response using the
    rsp_alloc_cb provided */        
    if ( rx_measure_data->override_callback_fp != NULL )
    {
      ftm_rf_test_rx_measure_tech_override_data_type tech_override_data;

      memset(&tech_override_data, 0, sizeof(ftm_rf_test_rx_measure_tech_override_data_type) );

      tech_override_data.req_prop_num = req_data->payload.num_of_properties;
      tech_override_data.req_prop_list = &(req_data->payload.property_data);
      tech_override_data.rsp_allocator_cb_data = &(command->response_data);
      tech_override_data.rsp_alloc_cb = rx_measure_rsp_default_response_helper;
      
      ec_tech_cb = rx_measure_data->override_callback_fp( &tech_override_data );

      tech_override = TRUE;
    }
    else /* if ( rx_measure_data->override_callback_fp == NULL )*/
    {
      /* Unpack data */
      ec_unpack = ftm_rf_test_unpack_property_list( 
                                        req_data->payload.num_of_properties, 
                                        &(req_data->payload.property_data),
                                        rx_measure_data,
                                        TRUE,
                                        rx_measure_req_default_unpack_cb,
                                        rx_measure_req_default_delimiter_cb);
      
      /* Continue if the UNPACK error code is 0 */
      if ( ec_unpack == 0 )
      {
        /* Call Tech callback */
        if ( rx_measure_data->callback_fp != NULL )
        {
          ec_tech_cb = rx_measure_data->callback_fp( rx_measure_data->unpacked_data, 
                                                     rx_measure_data->unpacked_data_num );

        } /* if ( rx_measure_data->mode_data[command_instance->technology].callback_fp != NULL ) */
        else
        {
          ec_tech_cb = (1<<FTM_RF_TEST_RX_EC_SUCCESS);
        } /* if ! ( rx_measure_data->mode_data[command_instance->technology].callback_fp != NULL ) */
        
      } /* if ( ec_unpack == 0 ) */
      else
      {
        FTM_MSG( FTM_ERROR, "[FTM.RFTEST][RX_MEASURE]rx_measure_handler: Unpack failure" );
      }

    }/* if ( rx_measure_data->override_callback_fp == NULL ) */

    /* Accumulate error code */
    error_code |= ec_unpack;
    error_code |= ec_tech_cb;

    if ( error_code != 0 )
    {
      ret_val = FALSE;
    } /* if ( error_code != 0 ) */

    FTM_MSG_1( FTM_ERROR, "[FTM.RFTEST][RX_MEASURE][DISPATCH]: [ErrorCode 0x%x]", error_code );
  }

  /* Populate respoonse payload, if tech did not override common unpack & dispatch */
  if ( ret_val == TRUE && tech_override == FALSE )
  {
    uint32 payload_size = 0;

    ret_val &= rx_measure_rsp_default_repack_helper( rx_measure_data->unpacked_data_num,
                                                 rx_measure_data->unpacked_data,
                                                 &(rx_measure_data->rsp_payload_data),
                                                 &payload_size,                                                
                                                 TRUE);

    rx_measure_data->rsp_payload_data.error_code = error_code;

    ret_val = rx_measure_rsp_default_response_helper( &(command->response_data),
                                                &(rx_measure_data->rsp_payload_data),
                                                payload_size );

  }/* if ( ret_val == TRUE && tech_overriden == FALSE )*/
  
  return ret_val; 

} /* radio_config_handler */

