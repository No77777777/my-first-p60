/*!
  @brief
  Call back API to allow common unpacker to identify delimter from property list 
*/
static boolean
rx_measure_req_default_delimiter_cb
(
   uint32 property_type
)
{
  boolean is_delimiter = FALSE;

  if ( property_type == FTM_RX_MEASURE_PROP_RX_CARRIER )
  {
    is_delimiter = TRUE;
  }
  else
  {
    is_delimiter = FALSE;
  }
  
  return is_delimiter;
}


