/*--------------------------------------------------------------------------------------------------------------------*/
/*!
  @brief
  Initialize Rx Measure Command handler module
 
  @details
  This function initializes the Rx Measureure command module. Initialization includes, allocating the memory for
  house keeping data for Rx Measure command and populating the command handler function
 
  @param dispatch_data
  Poitner to dispatch data specific to Rx Measure command
 
  @return
  Flag indicating the status of Rx Measure initialization
*/
boolean
ftm_rf_test_rx_measure_init
(
  ftm_rf_test_command_dispatch_data_t *dispatch_data
)
{
  boolean ret_val = TRUE;

  /* Param Validation */
  if ( dispatch_data == NULL )
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][RX_MEASURE]ftm_rf_test_rx_measure_init: Null param" );
    return FALSE;
  } /* if ( dispatch_data == NULL ) */

  /* Allocate memory for Rx Measure command handler */ 

  if ( dispatch_data->command_data == NULL )
  {
    dispatch_data->command_data = 
      (void*)modem_mem_alloc( sizeof(ftm_rf_test_rx_measure_command_data_t), MODEM_MEM_CLIENT_RFA );
  } /* if ( dispatch_data->command_data == NULL ) */

  if ( dispatch_data->command_data != NULL )
  {
    memset( dispatch_data->command_data, 0, sizeof(ftm_rf_test_rx_measure_command_data_t) );
    dispatch_data->command_handler = rx_measure_handler;
  } /* if ( dispatch_data->command_data != NULL ) */
  else
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][RX_MEASURE]ftm_rf_test_rx_measure_init: Malloc failure" );
    ret_val = FALSE;
  } /* if !( dispatch_data->command_data != NULL ) */

  return ret_val;

} /* ftm_rf_test_rx_measure_init */

/*--------------------------------------------------------------------------------------------------------------------*/
/*!
  @brief
  DeInitialize Rx Measure Command handler module
 
  @details
  This function deinitializes the Rx Measureure command module. DeInitialization includes, deallocating the memory for
  house keeping data for Rx Measure command
 
  @param dispatch_data
  Poitner to dispatch data specific to Rx Measure command
 
  @return
  Flag indicating the status of Rx Measure deinitialization
*/
boolean
ftm_rf_test_rx_measure_deinit
(
  ftm_rf_test_command_dispatch_data_t *dispatch_data
)
{
  boolean ret_val = TRUE;

  /* Param Validation */
  if ( dispatch_data == NULL )
  {
    FTM_MSG( FTM_ERROR, "[FTM.RFTEST][RADIO_CONFIG]ftm_rf_test_radio_config_deinit: Null param" );
    return FALSE;
  } /* if ( dispatch_data == NULL ) */

  ftm_rf_test_rx_measure_command_data_t * rx_measure_data = 
    (ftm_rf_test_rx_measure_command_data_t *)dispatch_data->command_data;

  /* Free memory allocated for Radio Config command handler */ 
  if ( rx_measure_data != NULL )
  {
    uint8 mode_idx = 0;
    for ( mode_idx = 0; mode_idx < RFM_NUM_MODES; mode_idx ++ )
    {
      if( rx_measure_data->mode_data[mode_idx].unpacked_data != NULL )
      {
        modem_mem_free( rx_measure_data->mode_data[mode_idx].unpacked_data, MODEM_MEM_CLIENT_RFA );
      }

      if ( rx_measure_data->mode_data[mode_idx].rsp_payload_data.result_prop_list != NULL )
      {
        modem_mem_free( rx_measure_data->mode_data[mode_idx].rsp_payload_data.result_prop_list, MODEM_MEM_CLIENT_RFA );
      }
    }

    modem_mem_free( rx_measure_data , MODEM_MEM_CLIENT_RFA );

    dispatch_data->command_data = NULL;
  } /* if ( dispatch_data->command_data != NULL ) */

  dispatch_data->command_handler = NULL;

  return ret_val;

} /* ftm_rf_test_rx_measure_deinit */

